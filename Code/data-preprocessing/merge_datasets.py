#!/usr/bin/env python3
"""
Merge Datasets — Combines two ASL datasets into a balanced, unified dataset.

Given two ASL dataset directories (each with A-Z subdirectories), this script
selects a fixed number of images from each dataset per alphabet letter and
merges them into a single output directory.

Uses a fixed random seed for reproducible, unbiased sampling — ensuring that
the exact same subset is selected on every run.

Features:
    - Balanced sampling: same number of images per alphabet from each dataset
    - Reproducible: fixed random seed (default: 42)
    - Supports per-letter overrides (e.g., use only one dataset for certain letters)
    - Optional confidence-based quality filtering via a CSV from preprocess.py
    - Full traceability via merge_report.csv

Usage:
    # Basic merge: 500 from each dataset per alphabet
    python3 Code/data-preprocessing/merge_datasets.py \\
        --dataset1 data/processed_asl \\
        --dataset2 data/signalphaset \\
        --output data/merged_asl_dataset 

    # With overrides for specific letters
    python3 Code/data-preprocessing/merge_datasets.py \
        --dataset1 data/processed_asl \
        --dataset2 data/signalphaset \
        --output data/merged_asl_dataset \
        --dataset2-only D,G,M,N,P,T,X,Z  \
        --dataset1-only J

    # With confidence filtering on dataset1
    python3 Code/data-preprocessing/merge_datasets.py \
        --dataset1 ~/Downloads/87k-cropped \
        --dataset2 ~/Downloads/26k-asl \
        --output ~/Downloads/merged-asl \
        --confidence-csv data/processed_asl/confidence_scores.csv \
        --confidence-threshold 0.7
"""

import argparse
import csv
import os
import random
import shutil
import sys
import time

from crop_hands import IMAGE_EXTENSIONS


# ── Image collection ─────────────────────────────────────────────────────────

def collect_letter_images(dataset_dir: str) -> dict[str, list[str]]:
    """Scan a dataset directory and return a dict mapping letter → list of image paths.

    Expects a directory structure like:
        dataset_dir/A/*.jpg
        dataset_dir/B/*.jpg
        ...
        dataset_dir/Z/*.jpg
    """
    letter_images: dict[str, list[str]] = {}

    if not os.path.isdir(dataset_dir):
        print(f"❌  Directory does not exist: {dataset_dir}")
        sys.exit(1)

    for entry in sorted(os.listdir(dataset_dir)):
        entry_path = os.path.join(dataset_dir, entry)
        if not os.path.isdir(entry_path):
            continue

        images = []
        for fname in sorted(os.listdir(entry_path)):
            ext = os.path.splitext(fname)[1].lower()
            if ext in IMAGE_EXTENSIONS:
                images.append(os.path.join(entry_path, fname))

        if images:
            letter_images[entry] = images

    return letter_images


def load_confidence_scores(csv_path: str) -> dict[str, float]:
    """Load confidence scores from a CSV generated by preprocess.py.

    Returns a dict mapping relative_path → confidence_score.
    """
    scores: dict[str, float] = {}

    with open(csv_path, "r") as f:
        reader = csv.DictReader(f)
        for row in reader:
            rel_path = row["relative_path"]
            score = float(row["confidence_score"])
            scores[rel_path] = score

    return scores


# ── Merge logic ──────────────────────────────────────────────────────────────

def merge_datasets(
    dataset1_dir: str,
    dataset2_dir: str,
    output_dir: str,
    count_per_dataset: int = 500,
    seed: int = 42,
    dataset1_only: set[str] | None = None,
    dataset2_only: set[str] | None = None,
    confidence_scores: dict[str, float] | None = None,
    confidence_threshold: float = 0.0,
) -> None:
    """Merge two ASL datasets into a single balanced dataset.

    Parameters
    ----------
    dataset1_dir : str
        Path to first dataset (e.g., 87k-cropped).
    dataset2_dir : str
        Path to second dataset (e.g., 26k-asl).
    output_dir : str
        Path for merged output.
    count_per_dataset : int
        Number of images to sample from each dataset per letter (default: 500).
        For single-source letters, this is doubled (1,000 total from one source).
    seed : int
        Random seed for reproducible sampling (default: 42).
    dataset1_only : set[str] or None
        Letters to source exclusively from dataset1 (e.g., {"J"}).
    dataset2_only : set[str] or None
        Letters to source exclusively from dataset2 (e.g., {"D","G","M",...}).
    confidence_scores : dict or None
        Optional confidence scores for dataset1 images (from preprocess.py).
    confidence_threshold : float
        Minimum confidence score for dataset1 images (default: 0.0 = no filter).
    """
    dataset1_only = dataset1_only or set()
    dataset2_only = dataset2_only or set()
    total_per_letter = count_per_dataset * 2  # e.g., 500 + 500 = 1,000

    # ── Scan both datasets ───────────────────────────────────────────────
    print(f"📂  Dataset 1: {os.path.abspath(dataset1_dir)}")
    ds1_images = collect_letter_images(dataset1_dir)
    print(f"     Found {sum(len(v) for v in ds1_images.values()):,} images "
          f"across {len(ds1_images)} letters")

    print(f"📂  Dataset 2: {os.path.abspath(dataset2_dir)}")
    ds2_images = collect_letter_images(dataset2_dir)
    print(f"     Found {sum(len(v) for v in ds2_images.values()):,} images "
          f"across {len(ds2_images)} letters")

    print(f"📂  Output:    {os.path.abspath(output_dir)}")
    print(f"🎲  Seed:      {seed}")
    print(f"📊  Target:    {total_per_letter} images per letter "
          f"({count_per_dataset} from each dataset)")
    print()

    if dataset1_only:
        print(f"  Dataset 1 only: {', '.join(sorted(dataset1_only))}")
    if dataset2_only:
        print(f"  Dataset 2 only: {', '.join(sorted(dataset2_only))}")
    if confidence_scores:
        print(f"  Confidence filter: threshold ≥ {confidence_threshold} "
              f"({len(confidence_scores):,} scores loaded)")
    print()

    # ── Determine all letters to process ─────────────────────────────────
    all_letters = sorted(set(ds1_images.keys()) | set(ds2_images.keys()))

    if not all_letters:
        print("❌  No letters found in either dataset.")
        sys.exit(1)

    # ── Process each letter ──────────────────────────────────────────────
    rng = random.Random(seed)
    report_rows: list[dict] = []
    letter_summary: list[dict] = []
    total_copied = 0
    start_time = time.time()

    for letter in all_letters:
        ds1_pool = ds1_images.get(letter, [])
        ds2_pool = ds2_images.get(letter, [])
        letter_dir = os.path.join(output_dir, letter)
        os.makedirs(letter_dir, exist_ok=True)

        # Apply confidence filter to dataset1 pool
        if confidence_scores and ds1_pool:
            filtered_ds1 = []
            for img_path in ds1_pool:
                # Build relative path to match CSV keys
                rel = os.path.join(letter, os.path.basename(img_path))
                score = confidence_scores.get(rel, -1.0)
                if score >= confidence_threshold:
                    filtered_ds1.append(img_path)
            ds1_pool = filtered_ds1

        # Determine source strategy for this letter
        if letter in dataset2_only:
            # Use only dataset2
            selected_ds1 = []
            need_from_ds2 = total_per_letter
            source_label = "dataset2-only"
        elif letter in dataset1_only:
            # Use only dataset1
            need_from_ds1 = total_per_letter
            selected_ds2 = []
            source_label = "dataset1-only"
        else:
            # Merge from both
            need_from_ds1 = count_per_dataset
            need_from_ds2 = count_per_dataset
            source_label = "merged"

        # Sample from dataset1 (unless dataset2-only)
        if letter not in dataset2_only:
            need = total_per_letter if letter in dataset1_only else count_per_dataset
            if len(ds1_pool) < need:
                print(f"  ⚠  Letter {letter}: dataset1 has only {len(ds1_pool)} "
                      f"images (need {need}), using all available")
                selected_ds1 = ds1_pool[:]
            else:
                selected_ds1 = rng.sample(ds1_pool, need)

        # Sample from dataset2 (unless dataset1-only)
        if letter not in dataset1_only:
            need = total_per_letter if letter in dataset2_only else count_per_dataset
            if len(ds2_pool) < need:
                print(f"  ⚠  Letter {letter}: dataset2 has only {len(ds2_pool)} "
                      f"images (need {need}), using all available")
                selected_ds2 = ds2_pool[:]
            else:
                selected_ds2 = rng.sample(ds2_pool, need)

        # Copy selected images to output
        copied = 0

        for img_path in selected_ds1:
            fname = os.path.basename(img_path)
            dst_name = f"ds1_{fname}"
            dst_path = os.path.join(letter_dir, dst_name)
            shutil.copy2(img_path, dst_path)
            copied += 1

            report_rows.append({
                "letter": letter,
                "source": "dataset1",
                "original_path": img_path,
                "output_filename": dst_name,
            })

        for img_path in selected_ds2:
            fname = os.path.basename(img_path)
            dst_name = f"ds2_{fname}"
            dst_path = os.path.join(letter_dir, dst_name)
            shutil.copy2(img_path, dst_path)
            copied += 1

            report_rows.append({
                "letter": letter,
                "source": "dataset2",
                "original_path": img_path,
                "output_filename": dst_name,
            })

        total_copied += copied
        ds1_count = len(selected_ds1) if letter not in dataset2_only else 0
        ds2_count = len(selected_ds2) if letter not in dataset1_only else 0

        letter_summary.append({
            "letter": letter,
            "source": source_label,
            "from_ds1": ds1_count,
            "from_ds2": ds2_count,
            "total": copied,
        })

        status = "✓" if copied == total_per_letter else "⚠"
        print(f"  {status} {letter}:  {ds1_count:>4} (ds1) + {ds2_count:>4} (ds2) = "
              f"{copied:>5} images  [{source_label}]")

    # ── Write merge report ───────────────────────────────────────────────
    report_path = os.path.join(output_dir, "merge_report.csv")
    with open(report_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["letter", "source",
                                                "original_path",
                                                "output_filename"])
        writer.writeheader()
        writer.writerows(report_rows)

    # ── Write summary ────────────────────────────────────────────────────
    summary_path = os.path.join(output_dir, "merge_summary.txt")
    with open(summary_path, "w") as f:
        f.write(f"Merge Summary\n")
        f.write(f"{'='*60}\n")
        f.write(f"Dataset 1: {os.path.abspath(dataset1_dir)}\n")
        f.write(f"Dataset 2: {os.path.abspath(dataset2_dir)}\n")
        f.write(f"Output:    {os.path.abspath(output_dir)}\n")
        f.write(f"Seed:      {seed}\n")
        f.write(f"Target:    {total_per_letter} per letter\n")
        f.write(f"\n")
        f.write(f"{'Letter':<8} {'Source':<15} {'DS1':>5} {'DS2':>5} {'Total':>6}\n")
        f.write(f"{'-'*42}\n")
        for s in letter_summary:
            f.write(f"{s['letter']:<8} {s['source']:<15} {s['from_ds1']:>5} "
                    f"{s['from_ds2']:>5} {s['total']:>6}\n")
        f.write(f"\nTotal images: {total_copied:,}\n")

    # ── Print final summary ──────────────────────────────────────────────
    elapsed = time.time() - start_time
    print(f"\n{'='*60}")
    print(f"  MERGE SUMMARY")
    print(f"{'='*60}")
    print(f"  Total images copied : {total_copied:,}")
    print(f"  Letters processed   : {len(all_letters)}")
    print(f"  Time                : {elapsed:.1f}s")
    print(f"  Merge report        : {report_path}")
    print(f"  Summary             : {summary_path}")
    print(f"{'='*60}")

    # Verify balance
    imbalanced = [s for s in letter_summary if s["total"] != total_per_letter]
    if imbalanced:
        print(f"\n  ⚠  {len(imbalanced)} letter(s) are imbalanced:")
        for s in imbalanced:
            print(f"     {s['letter']}: {s['total']} (expected {total_per_letter})")
    else:
        print(f"\n  ✅ All {len(all_letters)} letters have exactly "
              f"{total_per_letter} images each.")

    print()


# ── CLI ──────────────────────────────────────────────────────────────────────

def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Merge two ASL datasets into a balanced, unified dataset "
                    "with reproducible random sampling.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Examples:\n"
            "  # Basic merge: 500 from each dataset per alphabet\n"
            "  python merge_datasets.py \\\n"
            "      --dataset1 ~/Downloads/87k-cropped \\\n"
            "      --dataset2 ~/Downloads/26k-asl \\\n"
            "      --output ~/Downloads/merged-asl\n\n"
            "  # With per-letter overrides\n"
            "  python merge_datasets.py \\\n"
            "      --dataset1 ~/Downloads/87k-cropped \\\n"
            "      --dataset2 ~/Downloads/26k-asl \\\n"
            "      --output ~/Downloads/merged-asl \\\n"
            "      --dataset2-only D,G,M,N,P,T,X,Z \\\n"
            "      --dataset1-only J\n\n"
            "  # With confidence filtering\n"
            "  python merge_datasets.py \\\n"
            "      --dataset1 ~/Downloads/87k-cropped \\\n"
            "      --dataset2 ~/Downloads/26k-asl \\\n"
            "      --output ~/Downloads/merged-asl \\\n"
            "      --confidence-csv ~/Downloads/87k-cropped/confidence_scores.csv \\\n"
            "      --confidence-threshold 0.7\n"
        ),
    )

    parser.add_argument(
        "--dataset1", required=True,
        help="Path to first dataset directory (e.g., 87k-cropped). "
             "Must contain A-Z subdirectories.",
    )
    parser.add_argument(
        "--dataset2", required=True,
        help="Path to second dataset directory (e.g., 26k-asl). "
             "Must contain A-Z subdirectories.",
    )
    _default_output = os.path.join(os.path.dirname(os.path.abspath(__file__)), "merge_output")
    parser.add_argument(
        "--output", default=_default_output,
        help="Output directory for the merged dataset. "
             f"(default: {_default_output})",
    )
    parser.add_argument(
        "--count", type=int, default=500,
        help="Number of images to sample from EACH dataset per letter "
             "(default: 500, giving 1,000 total per letter).",
    )
    parser.add_argument(
        "--seed", type=int, default=42,
        help="Random seed for reproducible sampling (default: 42).",
    )
    parser.add_argument(
        "--dataset1-only", type=str, default="",
        help="Comma-separated letters to source exclusively from dataset1 "
             "(e.g., J). These letters get --count * 2 images from dataset1.",
    )
    parser.add_argument(
        "--dataset2-only", type=str, default="",
        help="Comma-separated letters to source exclusively from dataset2 "
             "(e.g., D,G,M,N,P,T,X,Z). These letters get --count * 2 "
             "images from dataset2.",
    )
    parser.add_argument(
        "--confidence-csv", type=str, default=None,
        help="Path to confidence_scores.csv from preprocess.py. "
             "Used to filter dataset1 images by detection confidence.",
    )
    parser.add_argument(
        "--confidence-threshold", type=float, default=0.0,
        help="Minimum confidence score for dataset1 images when using "
             "--confidence-csv (default: 0.0 = no filter).",
    )

    args = parser.parse_args()
    return args


def main() -> None:
    args = parse_args()

    # Parse letter overrides
    ds1_only = set()
    if args.dataset1_only:
        ds1_only = {l.strip().upper() for l in args.dataset1_only.split(",")}

    ds2_only = set()
    if args.dataset2_only:
        ds2_only = {l.strip().upper() for l in args.dataset2_only.split(",")}

    # Check for conflicts
    overlap = ds1_only & ds2_only
    if overlap:
        print(f"❌  Letters cannot be in both --dataset1-only and --dataset2-only: "
              f"{', '.join(sorted(overlap))}")
        sys.exit(1)

    # Load confidence scores if provided
    confidence_scores = None
    if args.confidence_csv:
        if not os.path.isfile(args.confidence_csv):
            print(f"❌  Confidence CSV not found: {args.confidence_csv}")
            sys.exit(1)
        confidence_scores = load_confidence_scores(args.confidence_csv)
        print(f"📋  Loaded {len(confidence_scores):,} confidence scores")

    os.makedirs(args.output, exist_ok=True)

    merge_datasets(
        dataset1_dir=args.dataset1,
        dataset2_dir=args.dataset2,
        output_dir=args.output,
        count_per_dataset=args.count,
        seed=args.seed,
        dataset1_only=ds1_only,
        dataset2_only=ds2_only,
        confidence_scores=confidence_scores,
        confidence_threshold=args.confidence_threshold,
    )


if __name__ == "__main__":
    main()
